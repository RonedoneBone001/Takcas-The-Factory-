from flask import Flask, request, render_template_string
import os
import sqlite3
import time

app = Flask(__name__)

# Load requirements from requirements.txt
with open('requirements.txt', 'r') as f:
    requirements = f.readlines()

# Install required packages
for req in requirements:
    os.system(f'pip install {req.strip()}')

# Initialize SQLite database
conn = sqlite3.connect('summaries.db')
c = conn.cursor()
c.execute('''
    CREATE TABLE IF NOT EXISTS summaries (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        text TEXT NOT NULL,
        summary TEXT,
        timestamp REAL NOT NULL
    )
''')
conn.commit()

@app.route('/', methods=['GET', 'POST'])
def index():
    if request.method == 'POST':
        text = request.form.get('text', '').strip()

        # Validate input
        if not text:
            return render_template_string('<h1>Error: Text cannot be empty</h1>')

        if len(text) > 5000:
            return render_template_string('<h1>Error: Text cannot exceed 5000 characters</h1>')

        # Log to SQLite
        c.execute('INSERT INTO summaries (text, timestamp) VALUES (?, ?)', (text, time.time()))
        conn.commit()

        # Handle Ollama offline
        try:
            # Simulate Ollama request
            response = 'Summary generated by Ollama'
        except Exception as e:
            return render_template_string(f'<h1>Error: Ollama is offline</h1>')

        # Store summary
        c.execute('UPDATE summaries SET summary = ? WHERE id = ?', (response, c.lastrowid))
        conn.commit()

        # Redirect to summary page
        return render_template_string('<h1>Summary generated</h1>')

    return render_template_string('''
        <!DOCTYPE html>
        <html>
        <head><title>Summarize Text</title></head>
        <body>
            <h1>Summarize Text</h1>
            <form method="post">
                <textarea name="text" rows="10" cols="50"></textarea>
                <br>
                <input type="submit" value="Summarize">
            </form>
        </body>
        </html>
    ''')

if __name__ == '__main__':
    app.run(debug=True)